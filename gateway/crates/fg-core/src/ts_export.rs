//! TypeScript contract generation.
//!
//! `render()` produces the content of `src/gateway/types.gen.ts` from the Rust types: one file,
//! declarations only, 64-bit integers mapped to `number` (timestamps are milliseconds, well
//! below 2^53). The file is committed; `tests/ts_types.rs` fails when it is stale, and
//! rewrites it when run with `FG_UPDATE_TYPES=1`.

