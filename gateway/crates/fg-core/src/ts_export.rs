/// Hand-written part of the contract: helper types that cannot be derived. Kept short; the
/// Rust test `collections_list_matches_the_typescript_prelude` ties it to `COLLECTIONS`.
pub const PRELUDE: &str = r"/** Patch of an entity: field groups are merged shallowly, other fields are replaced. */
export type PatchOf<T> = {
  [K in keyof T]?: T[K] extends readonly unknown[] ? T[K] : T[K] extends object ? Partial<T[K]> : T[K];
};

/** Collections carried by `up` frames: keyed entities, each a patch. */
export type Upsert = {
  bots?: Record<string, PatchOf<BotRow>>;
  wallets?: Record<string, PatchOf<WalletRow>>;
  positions?: Record<string, PatchOf<Position>>;
  alerts?: Record<string, PatchOf<Alert>>;
  events?: Record<string, PatchOf<Event>>;
  health?: Record<string, PatchOf<Health>>;
  scopes?: Record<string, PatchOf<ScopeTotals>>;
  details?: Record<string, PatchOf<BotDetail>>;
};
";

/// Tell prettier and eslint to leave the generated file alone, and say how it is produced.
const HEADER: &str = "/* eslint-disable */
// GENERATED by gateway/crates/fg-core (ts_export). DO NOT EDIT BY HAND.
// Regenerate: FG_UPDATE_TYPES=1 cargo test -p fg-core --test ts_types
// The contract test fails when this file is out of date.
";

/// Render the whole `types.gen.ts`.
#[must_use]
pub fn render() -> String {
    let cfg = Config::new().with_large_int("number");
    let mut out = String::from(HEADER);

    out.push_str("\n// ---- protocol constants ----\n");
    out.push_str(&format!(
        "export const GATEWAY_PROTOCOL_VERSION = {};\n",
        protocol::PROTOCOL_VERSION
    ));
    out.push_str(&format!(
        "export const HEARTBEAT_INTERVAL_S = {};\n",
        protocol::HEARTBEAT_INTERVAL_S
    ));
    out.push_str(&format!(
        "export const HEARTBEAT_TIMEOUT_S = {};\n",
        protocol::HEARTBEAT_TIMEOUT_S
    ));
    out.push_str(&format!(
        "export const AUTH_TIMEOUT_S = {};\n",
        protocol::AUTH_TIMEOUT_S
    ));
    out.push_str(&format!(
        "export const DELTA_BUFFER_SIZE = {};\n",
        protocol::DELTA_BUFFER_SIZE
    ));
    let backoff: Vec<String> = protocol::RECONNECT_BACKOFF_S
        .iter()
        .map(u64::to_string)
        .collect();
    out.push_str(&format!(
        "export const RECONNECT_BACKOFF_S = [{}];\n",
        backoff.join(", ")
    ));
    let colls: Vec<String> = protocol::COLLECTIONS
        .iter()
        .map(|c| format!("'{c}'"))
        .collect();
    out.push_str(&format!(
        "export const COLLECTIONS = [{}] as const;\n",
        colls.join(", ")
    ));

    macro_rules! section {
        ($title:literal; $($t:ty),+ $(,)?) => {
            out.push_str(concat!("\n// ---- ", $title, " ----\n"));
            $(
                out.push_str("export ");
                out.push_str(&<$t as TS>::decl(&cfg));
                out.push('\n');
            )+
        };
    }

    section!("identity"; BotKey);
    section!("model";
        Severity, Side, BotMode, BotStatus, FreshnessSource, Freshness, FreshnessGroup,
        BotIdentity, BotStateInfo, BotMetrics, AlertSummary, BotRow, Position, TradeRow,
        ReconStatus, ReconSummary, WalletRow, HealthLevel, HealthReason, Health, EventKind, Event,
        AuditEntry, Ticker, BotAlias, ScopeTotals, PairLock, BotConfigSummary, BotDetail,
        ActionStatus, ActionVerify, ActionResult, PrefsDoc,
    );
    section!("calculations";
        Market, PairInfo, DrawdownDef, ClosedPnl, OpenRisk, HistorySample, DrawdownInput,
        DrawdownValue, DrawdownResult, ExitKind, ExitClass, ExitReason, DurationLevel,
        CapitalSource, CapitalInput, Capital, CapitalSum, WalletReport, WalletTotals,
        ExposurePosition, Exposure, TradeTotals, Tz, PeriodKey, PeriodUnit, PnlBucket,
    );
    section!("alerts";
        AlertTypeId, AlertCategory, Direction, ThresholdSpec, RuleMeta, RuleConfig,
        AlertRulesConfig, LogLine, PositionCtx, BotAlertContext, Condition, Evaluation, AlertState,
        AlertView, Alert, Silence, TransitionKind, AlertTransition,
    );
    section!("protocol";
        Channel, ErrorCode, ApiError, ResyncReason, SeqCheck, ClientFrame, ServerFrame,
    );

    out.push_str("\n// ---- helpers (hand written) ----\n");
    out.push_str(PRELUDE);
    // Rust doc links ([`path`]) mean nothing in TypeScript: keep the code span only.
    out.replace("[`", "`").replace("`]", "`")
}
